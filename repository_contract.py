# -*- coding: utf-8 -*-
"""Shared repository API contract. Does not open any database."""
from __future__ import annotations
from typing import Protocol, Any, Optional, Sequence

class RepositoryContract(Protocol):
    def execute(self, sql: str, params: Sequence[Any] = ()) -> Any: ...
    def fetch_one(self, sql: str, params: Sequence[Any] = ()) -> Optional[dict[str, Any]]: ...
    def fetch_all(self, sql: str, params: Sequence[Any] = ()) -> list[dict[str, Any]]: ...
    def insert(self, sql: str, params: Sequence[Any] = ()) -> int: ...
    def transaction(self): ...
    def close(self) -> None: ...

REQUIRED_METHODS = ("execute", "fetch_one", "fetch_all", "insert", "transaction", "close")

def missing_repository_methods(candidate: Any) -> list[str]:
    """Return absent/non-callable methods; intentionally does not call them."""
    return [name for name in REQUIRED_METHODS if not callable(getattr(candidate, name, None))]
